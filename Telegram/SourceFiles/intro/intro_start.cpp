StartWidget::StartWidget(
	QWidget *parent,
	not_null<Main::Account*> account,
	not_null<Data*> data)
: Step(parent, account, data, true) {
	setMouseTracking(true);
	setTitleText(rpl::single(AppName.utf16()));
	// 서버 언어팩이 내장 문구를 덮어써 "official" 문구가 나오므로 직접 넣는다.
	setDescriptionText(rpl::single(
		u"Welcome to Jennygram.\nInternal messenger."_q));
	show();
}

void StartWidget::submit() {
	account().destroyStaleAuthorizationKeys();
	// Jennygram internal: the server has no QR login, go to the phone step.
	goNext<PhoneWidget>();
}

rpl::producer<QString> StartWidget::nextButtonText() const {
	return tr::lng_start_msgs();
}

rpl::producer<> StartWidget::nextButtonFocusRequests() const {
	return _nextButtonFocusRequests.events();
}

void StartWidget::activate() {
	Step::activate();
	setInnerFocus();
}

void StartWidget::setInnerFocus() {
	_nextButtonFocusRequests.fire({});
}

